-- Insurance agent invite-gated signup + first-login onboarding.
--
-- Invite links let an admin let an agent fill in their own signup details
-- (instead of the admin typing them in via /api/admin/create-user), while
-- keeping the page unusable to anyone who didn't receive a link. The admin
-- only ever generates/sends a link *after* payment has already been
-- confirmed offline, so a signup via a valid token is created status:
-- 'active' immediately — no temp password, no manual activation step.
CREATE TABLE IF NOT EXISTS public.agent_invites (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    token           text NOT NULL,
    app_type        text NOT NULL DEFAULT 'insurance',
    role            text NOT NULL DEFAULT 'agent',
    invited_name    text,
    invited_email   text,
    status          text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'used', 'revoked')),
    created_by      uuid REFERENCES public.profiles(id),
    created_at      timestamptz NOT NULL DEFAULT now(),
    expires_at      timestamptz NOT NULL DEFAULT (now() + interval '14 days'),
    used_at         timestamptz,
    used_by         uuid REFERENCES public.profiles(id),
    UNIQUE (token)
);

CREATE INDEX IF NOT EXISTS idx_agent_invites_token ON public.agent_invites (token);

COMMENT ON TABLE public.agent_invites IS 'Single-use signup links generated by an admin after payment is confirmed offline. See app/api/insurance/signup and app/api/admin/insurance/invites.';

-- RLS on, no client policies — all access via service-role server routes
-- (admin invite management + token validation at signup), same pattern as
-- the knowledge/rates/SORA/economic-calendar tables.
ALTER TABLE public.agent_invites ENABLE ROW LEVEL SECURITY;

-- First-login onboarding progress for insurance agents. jsonb (rather than
-- separate columns) since the checklist is expected to grow steps over time.
ALTER TABLE public.profiles
    ADD COLUMN IF NOT EXISTS onboarding jsonb NOT NULL DEFAULT '{}'::jsonb;

-- Existing agents should never be forced through onboarding retroactively —
-- only agents created from this point on start with completed_at: null.
UPDATE public.profiles
SET onboarding = jsonb_build_object('completed_at', now(), 'profile_completed', true, 'tour_completed', true)
WHERE onboarding = '{}'::jsonb;
