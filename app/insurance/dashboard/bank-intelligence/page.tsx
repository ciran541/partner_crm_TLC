'use client'

import { useEffect, useMemo, useState } from 'react'
import { Landmark } from 'lucide-react'
import Spinner from '@/components/shared/Spinner'
import EmptyState from '@/components/shared/EmptyState'
import BankReportCard from '@/components/insurance/bank-intelligence/BankReportCard'
import { BANK_SOURCES, type BankIntelligenceReport } from '@/lib/types/bankIntelligence'

function monthLabel(period: string): string {
    return new Date(`${period}T00:00:00Z`).toLocaleDateString('en-SG', { month: 'long', year: 'numeric', timeZone: 'UTC' })
}

export default function BankIntelligencePage() {
    const [reports, setReports] = useState<BankIntelligenceReport[]>([])
    const [loading, setLoading] = useState(true)
    const [fetchErr, setFetchErr] = useState<string | null>(null)
    const [bankFilter, setBankFilter] = useState('')

    useEffect(() => {
        setLoading(true)
        fetch('/api/insurance/bank-intelligence')
            .then(r => r.ok ? r.json() : Promise.reject('Failed'))
            .then(d => setReports(d.data ?? []))
            .catch(() => setFetchErr("Could not load Banks' Insights. Please refresh."))
            .finally(() => setLoading(false))
    }, [])

    const filtered = useMemo(() => {
        if (!bankFilter) return reports
        return reports.filter(r => r.bank_key === bankFilter)
    }, [reports, bankFilter])

    if (loading) return <div className="flex justify-center py-24"><Spinner /></div>
    if (fetchErr) return <div className="card text-center py-12 text-sm text-red-500">{fetchErr}</div>

    // filtered reports already sorted by report_period desc from the API — group while preserving that order.
    const groups: { period: string; reports: BankIntelligenceReport[] }[] = []
    for (const r of filtered) {
        const g = groups.find(g => g.period === r.report_period)
        if (g) g.reports.push(r)
        else groups.push({ period: r.report_period, reports: [r] })
    }

    return (
        <div className="max-w-3xl mx-auto space-y-5">
            <div>
                <h1 className="ios-page-title flex items-center gap-2">
                    <Landmark size={24} className="text-[#03a9e7]" /> Banks&apos; Insights
                </h1>
                <p className="page-subtitle">Monthly house-view research from major banks. </p>
            </div>

            <div className="flex flex-wrap gap-2">
                <button
                    onClick={() => setBankFilter('')}
                    className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition-all ${
                        !bankFilter ? 'bg-[#052d4a] text-white' : 'bg-slate-100 text-slate-500 hover:bg-slate-200'
                    }`}
                >
                    All
                </button>
                {BANK_SOURCES.map(s => (
                    <button
                        key={s.key}
                        onClick={() => setBankFilter(s.key)}
                        className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition-all ${
                            bankFilter === s.key ? 'bg-[#052d4a] text-white' : 'bg-slate-100 text-slate-500 hover:bg-slate-200'
                        }`}
                    >
                        {s.name}
                    </button>
                ))}
            </div>

            {groups.length === 0 ? (
                <EmptyState
                    icon={Landmark}
                    iconColor="#03a9e7"
                    title={bankFilter ? 'No reports from this bank yet' : 'No reports published yet'}
                    description={bankFilter ? 'Try a different bank filter.' : 'New monthly reports are checked for automatically. Check back soon, or ask your admin to trigger a refresh.'}
                />
            ) : (
                <div className="space-y-6">
                    {groups.map(g => (
                        <div key={g.period}>
                            <h2 className="text-xs font-bold text-slate-400 uppercase tracking-widest mb-2">{monthLabel(g.period)}</h2>
                            <div className="space-y-3">
                                {g.reports.map(r => <BankReportCard key={r.id} report={r} />)}
                            </div>
                        </div>
                    ))}
                </div>
            )}

            <p className="text-xs text-slate-400 mt-4 text-center">
                Sources: OCBC · UOB · HSBC · Maybank · SC · DBS &nbsp;·&nbsp; Summaries generated by AI from each bank&apos;s own published report
            </p>
        </div>
    )
}
